function buildPlayerIndex(){
  const index = new Map();
  WORLD_CUPS.forEach(wc => {
    const all = [...wc.topScorers, ...wc.otherScorers];
    all.forEach(p => {
      const key = p.name.trim();
      if(!index.has(key)) index.set(key, {name:p.name, country:p.country, appearances:[]});
      index.get(key).appearances.push({year:wc.year, goals:p.goals, host:wc.host});
    });
  });
  return [...index.values()].map(p => ({
    ...p,
    totalGoals: p.appearances.reduce((s,a)=>s+(a.goals||0),0)
  }));
}
const PLAYER_INDEX = buildPlayerIndex();

